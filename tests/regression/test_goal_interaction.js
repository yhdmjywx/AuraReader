const assert = require('node:assert/strict');
const { ui, click, input } = require('../helpers/react-workbench.cjs');
(async () => {
    const note = { id: 'n', bookId: 'a', kind: 'note', quote: 'Source', comment: 'My own words', page: 1 };
    const c = await require('../helpers/goal-workbench.cjs').goalWorkbench(undefined, [note]);
    try {
        const { goals, elements, storage } = c;
        await click('#goal-new');
        await input('#goal-panel textarea', 'A question\n我的阅读意图');
        const root = goals.edit.draft.id;
        assert.equal(goals.state.goals.length, 0, 'a new draft is not yet a committed Goal');
        const editor = document.querySelector('#goal-panel textarea');
        editor.setSelectionRange(3, 3);
        await ui(() => goals.refreshAnnotations());
        assert.equal(document.querySelector('#goal-panel textarea'), editor);
        assert.equal(editor.selectionStart, 3, 'view updates retain the caret');
        await ui(() => editor.dispatchEvent(new window.KeyboardEvent('keydown', { key: 'Enter', ctrlKey: true, isComposing: true, bubbles: true })));
        assert.ok(goals.edit, 'IME Enter does not finish the draft');
        await ui(() => goals.finishInlineEdit());
        assert.equal(goals.state.goals[0].text, 'A question\n我的阅读意图');
        assert.equal(document.querySelector('.goal-row').dataset.goalKind, 'root', 'root rows expose their parent-level presentation');
        await click('.goal-child');
        assert.equal(goals.selected, root);
        const originalRootText = goals.state.goals[0].text;
        await click('.goal-edit'); await input('#goal-panel textarea', originalRootText + '\n');
        await ui(() => goals.finishInlineEdit());
        assert.equal(document.querySelector('.goal-row-label').textContent, originalRootText, 'terminal blank lines do not enlarge the displayed row');
        await click('.goal-edit');
        assert.equal(document.querySelector('#goal-panel textarea').value, originalRootText, 'inline input opens without terminal blank rows');
        await ui(() => goals.finishInlineEdit());
        assert.equal(goals.state.goals[0].text, originalRootText + '\n', 'opening and closing an unchanged editor preserves the original stored text');
        await click('#goal-new'); await input('#goal-panel textarea', 'Child question');
        const child = goals.edit.draft.id;
        await ui(() => goals.finishInlineEdit());
        assert.equal(document.querySelector('.goal-row').dataset.goalKind, 'child', 'nested rows retain child-level presentation');
        assert.equal(goals.state.goals.find(g => g.id === child).parentId, root);
        await click('.goal-child-edit');
        assert.equal(goals.selected, root, 'editing a child preserves the active parent');
        assert.ok(document.querySelector('.goal-row > .goal-editor.is-inline textarea'), 'child edits in its own row');
        assert.equal(document.querySelector('.goal-title').textContent, 'A question\n我的阅读意图');
        await input('#goal-panel textarea', 'Child question revised');
        assert.equal(document.querySelector('.goal-editor-measure').textContent, 'Child question revised', 'inline measurement follows native input');
        assert.equal(document.querySelector('.goal-editor-measure').getAttribute('aria-hidden'), 'true', 'measurement text is not announced twice');
        await ui(() => goals.finishInlineEdit());
        assert.equal(goals.state.goals.find(g => g.id === child).text, 'Child question revised');
        assert.equal(goals.state.goals.find(g => g.id === root).text, originalRootText + '\n', 'child edit does not overwrite its parent');
        await click('.goal-child');
        await ui(() => goals.linkAnnotation(note.id));
        assert.equal(document.querySelectorAll('#goal-panel .goal-item').length, 1);
        assert.equal(document.querySelector('.goal-items-toggle'), null, 'region identifiers do not collapse content');
        assert.ok(document.querySelector('#goal-panel .goal-item'));
        await ui(() => goals.linkAnnotation(note.id));
        assert.equal(goals.state.links.length, 1, 'linking again keeps one relation');
        assert.ok(document.querySelector('.goal-item-text').textContent.includes(note.comment));
        assert.equal(document.querySelector('.goal-material-quote').textContent, note.quote, 'a linked note keeps its source alongside the reader comment');
        assert.equal(document.querySelector('.goal-material-comment').textContent, note.comment);
        assert.equal(document.querySelector('.goal-item-text').firstElementChild.className, 'goal-material-quote', 'source precedes the comment');
        await click('.goal-title');
        assert.equal(goals.selected, child);
        assert.equal(document.querySelector('#goal-panel textarea'), null, 'selecting the current Goal does not start editing');
        await click('.goal-edit');
        assert.ok(document.querySelector('.goal-title-row > .goal-editor.is-inline textarea'), 'existing Goal edits in its title slot');
        assert.equal(document.querySelectorAll('.goal-editor').length, 1, 'editing does not add a second editor below the title');
        await input('#goal-panel textarea', 'Revised child');
        await ui(() => goals.finishInlineEdit());
        const panel = elements.goalPanel;
        await ui(() => goals.openPage());
        assert.equal(document.querySelector('#goal-page-content #goal-panel'), panel, 'full page shares the same Goal view');
        assert.equal(document.querySelector('.goal-title').textContent, 'Revised child');
        assert.equal(document.querySelector('#goal-page .goal-material-quote').textContent, note.quote, 'full Goal view retains the same source');
        await ui(() => { note.quote = '  '; goals.refreshAnnotations(); });
        assert.equal(document.querySelector('.goal-material-quote'), null, 'missing source leaves no empty quote frame');
        assert.equal(document.querySelector('.goal-material-comment').textContent, note.comment);
        await ui(() => { note.quote = 'Source\nSecond paragraph'; note.comment = ''; goals.refreshAnnotations(); });
        assert.equal(document.querySelector('.goal-material-quote').textContent, note.quote, 'quote-only materials preserve newlines');
        assert.equal(document.querySelector('.goal-material-comment'), null, 'quote-only materials have no empty comment block');
        note.comment = 'My own words';
        await click('[aria-label="Unlink"]'); await ui(() => goals.flush());
        assert.equal(goals.state.links.length, 0);
        assert.equal(storage.read('annotations', note.id).comment, note.comment, 'unlink retains the original note');
        console.log('PASS: React Goal draft/IME/caret, hierarchy, link/unlink, shared full-page view and SQLite persistence');
    } finally { await c.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
