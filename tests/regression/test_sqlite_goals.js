const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { DatabaseSync } = require('node:sqlite');
const { createDataStore } = require('../../src/server/dataStore');
const { verifyDatabase, backupDatabase } = require('../../src/server/storageMaintenance');
const root = path.resolve('.commandcode/goal-storage'); fs.mkdirSync(root, { recursive: true });
const directory = fs.mkdtempSync(path.join(root, 'run-'));
const now = new Date().toISOString();
const goal = (id, parentId = null) => ({ id, parentId, text: 'Why?\n自己的问题', origin: null, createdAt: now, updatedAt: now });
(async () => {
    let store = createDataStore(directory);
    const book = { id: 'a', title: 'A', pages: ['<p>Source</p>'], unknown: [null, false] };
    const version = store.saveBook({ opId: randomUUID(), expected: 0, book });
    const note = { id: 'n', bookId: 'a', kind: 'note', quote: 'Source', comment: 'My words', extra: { intact: true } };
    store.saveNote({ opId: randomUUID(), expected: 0, generation: version.generation, note });
    store.saveNote({ opId: randomUUID(), expected: 0, generation: version.generation, note: { ...note, id: 'h', kind: 'highlight', comment: '' } });
    store.close();
    // A real current-schema specimen, not a second implementation of migration.
    const legacy = new DatabaseSync(path.join(directory, 'aurareader.sqlite'));
    legacy.exec('DROP TABLE goal_states; PRAGMA user_version=1'); legacy.close();
    store = createDataStore(directory);
    assert.equal(store.one('PRAGMA user_version').user_version, 4);
    assert.deepEqual(store.books()[0].value, book); assert.deepEqual(store.notes(['a']).find(row => row.id === 'n').value, note);
    const state = { bookId: 'a', goals: [goal('g'), goal('child', 'g')], links: [{ goalId: 'g', annotationId: 'h' }, { goalId: 'child', annotationId: 'n' }] };
    const command = { opId: randomUUID(), expected: 0, generation: version.generation, state };
    assert.deepEqual(store.saveGoals(command), { revision: 1 }); assert.deepEqual(store.saveGoals(command), { revision: 1 });
    assert.throws(() => store.saveGoals({ ...command, opId: randomUUID() }), { status: 409 });
    assert.throws(() => store.saveGoals({ ...command, opId: randomUUID(), expected: 1, state: { ...state, goals: [goal('g', 'child'), goal('child', 'g')] } }), { status: 409 });
    const deletion = { opId: randomUUID(), expected: 1, generation: version.generation, id: 'h', bookId: 'a' };
    const removed = store.deleteNote(deletion); assert.equal(removed.goalState.revision, 2); assert.equal(removed.goalState.value.links.length, 1);
    assert.deepEqual(store.deleteNote(deletion), removed);
    const restore = extra => store.restore({ opId: randomUUID(), books: [book], notes: [], ...extra });
    restore({}); assert.equal(store.goals(['a'])[0].revision, 2, 'old backups do not clear Goals');
    restore({ goalStates: [{ bookId: 'a', goals: [{ ...goal('child', 'g'), text: 'Restored' }] }] });
    assert.equal(store.goals(['a'])[0].value.links.length, 1, 'omitted links preserve current links');
    restore({ goalStates: [{ bookId: 'a', goals: [goal('child', 'g')], links: [] }] });
    assert.equal(store.goals(['a'])[0].value.links.length, 0);
    const before = JSON.stringify(store.books());
    assert.throws(() => store.restore({ opId: randomUUID(), books: [{ ...book, title: 'Must roll back' }], notes: [], goalStates: [{ bookId: 'a', goals: [goal('bad', 'missing')], links: [] }] }));
    assert.equal(JSON.stringify(store.books()), before);
    assert.deepEqual(store.check(), { integrity: 'ok', foreignKeys: 0 });
    const backup = await backupDatabase(directory); assert.equal(verifyDatabase(backup.filename).integrity, 'ok');
    store.deleteBook({ opId: randomUUID(), expected: store.books()[0].revision, id: 'a' });
    assert.equal(store.goals(['a'])[0].deleted, true);
    const recreated = store.saveBook({ opId: randomUUID(), expected: store.books()[0].revision, book });
    assert.notEqual(recreated.generation, version.generation);
    assert.throws(() => store.saveGoals({ ...command, opId: randomUUID(), expected: store.goals(['a'])[0].revision }), { status: 409 });
    store.close();
    const { createDesktopStorage } = require('../../src/desktop/storage.cjs');
    const desktop = createDesktopStorage(fs.mkdtempSync(path.join(root, 'ipc-'))); await desktop.call('createLibrary');
    const bv = await desktop.call('saveBook', { opId: randomUUID(), expected: 0, book });
    await desktop.call('saveGoals', { opId: randomUUID(), expected: 0, generation: bv.generation, state: { ...state, links: [] } });
    assert.deepEqual((await desktop.call('queryGoals', { bookIds: ['a'] })).records[0].value.goals, state.goals);
    await desktop.call('restore', { opId: randomUUID(), books: [book], notes: [], goalStates: [{ bookId: 'a', goals: [{ ...goal('child', 'g'), text: 'Partial desktop restore' }] }] });
    assert.equal((await desktop.call('queryGoals', { bookIds: ['a'] })).records[0].value.goals.find(goal => goal.id === 'child').text, 'Partial desktop restore');
    await assert.rejects(desktop.call('saveGoals', { ...command, unwanted: true }));
    desktop.close();
    console.log('Goal SQLite: current DB upgrade, validation, CAS/idempotence, delete cleanup, restore/rollback, backup and desktop dispatcher passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
