const assert = require('node:assert/strict');
const { JSDOM } = require('jsdom');
(async () => {
    const dom = new JSDOM('<div id="outer"><aside id="side"><div id="panel"></div><div id="handle" tabindex="0"></div></aside><main id="reader"></main></div><button id="toggle"></button>', { url: 'http://localhost' });
    global.localStorage = dom.window.localStorage;
    const { GoalSidebar } = await import('../../dist/client/features/goals/goalLayout.js');
    const d = dom.window.document;
    const elements = { readingWorkspace: d.getElementById('outer'), goalSidebar: d.getElementById('side'), goalPanel: d.getElementById('panel'), goalResizer: d.getElementById('handle'), workspaceContainer: d.getElementById('reader'), btnGoals: d.getElementById('toggle') };
    let total = 1440, mode = 'single', rejectFinish = false, savedAnchors = 0;
    Object.defineProperty(elements.readingWorkspace, 'clientWidth', { get: () => total });
    let captured = null;
    const handle = elements.goalResizer;
    handle.setPointerCapture = id => { captured = id; };
    handle.hasPointerCapture = id => captured === id;
    handle.releasePointerCapture = () => { captured = null; handle.dispatchEvent(new dom.window.Event('lostpointercapture')); };
    const sidebar = new GoalSidebar(elements, () => sidebar.update(mode), async () => { if (rejectFinish) throw new Error('unsaved'); }, () => savedAnchors++);
    const pointer = (type, x) => {
        const event = new dom.window.MouseEvent(type, { clientX: x, button: 0, bubbles: true, cancelable: true });
        Object.defineProperty(event, 'pointerId', { value: 7 }); handle.dispatchEvent(event); return event;
    };
    sidebar.update(mode);
    assert.equal(elements.goalSidebar.style.width, '280px');
    const field = d.createElement('textarea'); field.value = 'Keep the editor'; elements.goalPanel.append(field); field.focus(); field.setSelectionRange(4, 4);
    assert.equal(pointer('pointerdown', 280).defaultPrevented, true);
    pointer('pointermove', 490);
    assert.equal(elements.goalSidebar.style.width, '490px'); assert.equal(localStorage.getItem('aura_goal_sidebar_width'), null);
    assert.equal(d.activeElement, field); assert.equal(field.selectionStart, 4);
    pointer('pointerup', 490); assert.equal(localStorage.getItem('aura_goal_sidebar_width'), '490');
    pointer('pointerdown', 490); pointer('pointermove', 600); pointer('pointercancel', 600);
    assert.equal(elements.goalSidebar.style.width, '490px'); assert.equal(localStorage.getItem('aura_goal_sidebar_width'), '490');
    let readerKeys = 0; d.addEventListener('keydown', () => readerKeys++);
    handle.dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'ArrowLeft', bubbles: true, cancelable: true }));
    assert.equal(elements.goalSidebar.style.width, '480px'); assert.equal(readerKeys, 0, 'splitter arrows never turn a book page');
    pointer('pointerdown', 480); pointer('pointermove', 600);
    d.dispatchEvent(new dom.window.KeyboardEvent('keydown', { key: 'Escape', bubbles: true, cancelable: true }));
    assert.equal(elements.goalSidebar.style.width, '480px');
    total = 1100; sidebar.update(mode); assert.equal(elements.goalSidebar.style.width, '380px');
    assert.equal(localStorage.getItem('aura_goal_sidebar_width'), '480', 'narrow windows do not overwrite the preferred width');
    elements.workspaceContainer.style.margin = '8px'; sidebar.update(mode);
    assert.equal(elements.goalSidebar.style.width, '364px', 'surface gutters preserve the existing 720px reading space');
    assert.equal(localStorage.getItem('aura_goal_sidebar_width'), '480');
    total = 956; sidebar.update(mode); assert.equal(elements.goalSidebar.hidden, false);
    total = 955; sidebar.update(mode); assert.equal(elements.goalSidebar.hidden, true, 'sidebar availability accounts for actual surface margins');
    elements.workspaceContainer.style.margin = '';
    total = 800; sidebar.update(mode); assert.equal(elements.goalPanel.hidden, true);
    total = 1440; sidebar.update(mode); assert.equal(elements.goalSidebar.style.width, '480px');
    mode = 'double'; sidebar.update(mode); assert.equal(elements.goalSidebar.hidden, true);
    mode = 'single'; sidebar.update(mode);
    elements.btnGoals.click(); await new Promise(resolve => setImmediate(resolve)); assert.equal(elements.goalSidebar.hidden, true);
    elements.btnGoals.click(); await new Promise(resolve => setImmediate(resolve)); assert.equal(elements.goalSidebar.hidden, false);
    rejectFinish = true; elements.btnGoals.click(); await new Promise(resolve => setImmediate(resolve)); assert.equal(elements.goalSidebar.hidden, false, 'unsaved Goal stays accessible');
    const restored = new GoalSidebar(elements, () => {}, async () => {}); assert.equal(restored.preferredWidth, 480);
    assert.ok(savedAnchors > 0); dom.window.close();
    console.log('Goal sidebar: live splitter preserves editor/caret, pointer cancel/Escape, keyboard isolation, width persistence, responsive clamping and failed-hide guard passed.');
})().catch(error => { console.error(error); process.exitCode = 1; });
