const assert = require('node:assert/strict');
const { ui, click, input, waitFor } = require('../helpers/react-workbench.cjs');
(async () => {
    const note = { id:'n', bookId:'a', kind:'note', quote:'Source', comment:'Original note', page:1 };
    const c = await require('../helpers/goal-workbench.cjs').goalWorkbench(undefined, [note]);
    try {
        const { goals, storage } = c;
        const { GoalHome } = await import('../../dist/client/features/goals/goalHome.js');
        const { goalArea } = await import('../../dist/client/domain/goalLifecycle.js');
        let root, child;
        await ui(async () => { root = await goals.createRoot('Root intention'); child = await goals.createGoal('Nested question', root); await goals.linkAnnotation(note.id); });
        const originals = { books: storage.read('books'), notes: storage.read('annotations') };
        c.home = new GoalHome(document.getElementById('goal-home'), { goals, coordinator: {}, currentBookId: () => c.bookId, finishAnnotations: async () => {}, beforeOpen() {} });
        await ui(() => c.home.open());
        await ui(() => goals.operate(root, 'complete'));
        assert.ok(goals.state.goals.every(g => !!g.completedAt));
        await ui(() => goals.undoLifecycle());
        assert.ok(goals.state.goals.every(g => !g.completedAt));
        await ui(() => goals.operate(root, 'archive')); await ui(() => c.home.showArea('archive'));
        await input('#home-goal-search', 'Nested');
        assert.equal(document.querySelector('#home-goal-folders [data-goal-id]').dataset.goalId, child);
        assert.match(document.querySelector('.goal-original-path').textContent, /Root intention.*Nested question/);
        await ui(() => goals.operate(root, 'unarchive'));
        await ui(() => { c.home.showArea('library'); c.home.navigate(root); });
        await click('.home-current-actions button'); await click('[data-operation="delete"]');
        assert.ok(document.querySelector('.ui-dialog[data-open]'));
        await click('.ui-dialog[data-open] .ui-dialog-actions button');
        assert.equal(goalArea(goals.state, root), 'library', 'cancel leaves the Goal unchanged');
        await click('.home-current-actions button'); await click('[data-operation="delete"]');
        await click('.ui-dialog[data-open] .ui-button-danger');
        await waitFor(() => !goals.lifecycleBusy);
        assert.equal(goalArea(goals.state, child), 'trash');
        await ui(() => goals.operate(child, 'restore-root'));
        assert.equal(goals.state.goals.find(g => g.id === child).parentId, null);
        await ui(() => goals.operate(root, 'purge'));
        assert.equal(goals.state.goals.some(g => g.id === root), false);
        assert.deepEqual(storage.read('books'), originals.books);
        assert.deepEqual(storage.read('annotations'), originals.notes);
        console.log('PASS: React Goal lifecycle views, archive/search, delete dialog, restore/purge and source preservation');
    } finally { await c.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
