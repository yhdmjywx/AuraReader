const assert = require('node:assert/strict');
const { validateLibrary } = require('../../src/server/goalLibrary');
(async () => {
    const { addGoal, changeGoal } = await import('../../dist/client/domain/goalEngine.js');
    const { operateGoal: op, goalArea, areaGoals, goalPath } = await import('../../dist/client/domain/goalLifecycle.js');
    let state = { goals: [], links: [], bookLinks: [] };
    for (const [id, parentId] of [['root',null],['child','root'],['grandchild','child'],['other',null],['old','root']]) state = addGoal(state,{id,parentId,text:id,origin:null});
    state.links = [{ goalId:'child', annotationId:'note', bookId:'book', generation:'v' }];
    state.bookLinks = [{goalId:'root', bookId:'book', generation:'v'}];
    const now = '2026-10-27T00:00:00.000Z';
    state = op(state,'child','complete',now);
    assert.ok(state.goals.find(g=>g.id==='grandchild').completedAt);
    assert.equal(state.goals.find(g=>g.id==='root').completedAt,undefined,'child never completes parent');
    state = op(state,'old','archive',now);
    state = op(state,'root','complete',now);
    assert.ok(state.goals.filter(g=>g.id!=='other').every(g=>g.completedAt),'parent completes every descendant, including archived ones');
    assert.equal(goalArea(state,'old'),'archive','completion keeps archive');
    state = op(state,'root','reopen',now);
    assert.ok(state.goals.find(g=>g.id==='child').completedAt,'reopening does not reopen children');
    state = op(state,'root','complete',now); state = op(state,'grandchild','reopen',now);
    assert.ok(state.goals.find(g=>g.id==='root').completedAt,'reopening a child never reopens parent');
    const fresh = addGoal(state,{id:'new',parentId:'root',text:'new',origin:null});
    assert.equal(fresh.goals.find(g=>g.id==='new').completedAt,undefined,'new child defaults to in progress under a completed parent');
    const archived = op(state,'root','archive',now);
    assert.equal(goalArea(archived,'grandchild'),'archive');
    assert.deepEqual(areaGoals(archived,'library',null).map(g=>g.id),['other']);
    assert.deepEqual(areaGoals(archived,'archive',null).map(g=>g.id),['root']);
    assert.equal(areaGoals(archived,'archive',null,'grandchild')[0].id,'grandchild');
    assert.equal(goalPath(archived,'grandchild'),'root / child / grandchild');
    assert.throws(()=>changeGoal(archived,'grandchild','edit'),/Restore/);
    assert.throws(()=>addGoal(archived,{id:'blocked',parentId:'child',text:'blocked',origin:null}),/Restore/);
    const restored = op(archived,'root','unarchive',now);
    assert.equal(goalArea(restored,'child'),'library'); assert.equal(goalArea(restored,'old'),'archive','independently archived descendants stay archived');
    assert.equal(goalArea(op(archived,'grandchild','unarchive',now),'grandchild'),'library','restoring nested branch clears required ancestor markers');
    const deletedChild = op(state,'grandchild','delete',now), deleted = op(deletedChild,'root','delete',now);
    assert.deepEqual(deleted.links,state.links); assert.deepEqual(deleted.bookLinks,state.bookLinks,'soft delete retains relations');
    assert.equal(goalArea(deleted,'old'),'trash');
    const fromTrash = op(deleted,'root','restore',now);
    assert.equal(goalArea(fromTrash,'grandchild'),'trash','independently deleted children remain deleted');
    assert.equal(goalArea(fromTrash,'old'),'archive','trash restore preserves archive status');
    const toRoot = op(deleted,'child','restore-root',now);
    assert.equal(toRoot.goals.find(g=>g.id==='child').parentId,null); assert.equal(goalArea(toRoot,'root'),'trash'); assert.equal(goalArea(toRoot,'child'),'library');
    assert.equal(goalArea(op(deleted,'child','restore',now),'root'),'library');
    const purged = op(deleted,'root','purge',now);
    assert.deepEqual(purged.goals.map(g=>g.id),['other']); assert.deepEqual(purged.links,[]); assert.deepEqual(purged.bookLinks,[]);
    assert.throws(()=>op(state,'root','purge'),/Recently deleted/);
    assert.equal(validateLibrary(deleted),deleted);
    for (const field of ['completedAt','archivedAt','deletedAt']) assert.throws(()=>validateLibrary({...state,goals:state.goals.map(g=>({...g,[field]:'bad-date'}))}));
    const deep = {goals:Array.from({length:12000},(_,i)=>({id:String(i),parentId:i?String(i-1):null,text:'Question',origin:null,createdAt:now,updatedAt:now})),links:[]};
    assert.equal(op(deep,'0','complete',now).goals.filter(g=>g.completedAt).length,12000);
    assert.equal(areaGoals(op(deep,'0','archive',now),'archive',null).length,1,'deep branches are iterative');
    console.log('Goal lifecycle: downward completion, independent reopening, archive inheritance, search/path/filter, restore variants, trash/purge, validation and 12,000-node trees passed.');
})().catch(error=>{console.error(error);process.exitCode=1;});
